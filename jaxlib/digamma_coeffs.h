// Shared `constexpr` polynomial coefficients, Taylor constants, and near-zero
// override tables for the CPU (Highway SIMD) and GPU (CUDA / ROCm) `digamma`
// kernels (`DigammaF32`, `DigammaF32WithF64`, and `DigammaF64`).
//
// All constants match `jax/_src/lax/digamma.py`. The polynomials below were
// generated by Chebyshev-node interpolation in `mpmath` (`cheb_poly` and
// `split_desc`), splitting the larger low-degree coefficients into descending
// `(hi, lo)` pairs and storing the small high-degree coefficients in ascending
// single-word form (where powers of `1 / z^2` or `d^2` keep single-word
// rounding error well below `(hi, lo)` working precision):
//
//   import mpmath, numpy as np
//   def cheb_poly(fn, a, b, n, dps=140):
//     with mpmath.workdps(dps):
//       a, b = mpmath.mpf(a), mpmath.mpf(b)
//       nodes = [(a + b)/2 + (b - a)/2 * mpmath.cos(mpmath.pi * (2*j + 1) /
//       (2*n))
//                for j in range(n)]
//       m = mpmath.matrix([[x**k for k in range(n)] for x in nodes])
//       c = mpmath.lu_solve(m, mpmath.matrix([fn(x) for x in nodes]))
//       return [c[k] for k in range(n)]  # ascending powers x^0 .. x^{n-1}
//
//   def split_desc(coeffs, dtype, dps=140):
//     with mpmath.workdps(dps):
//       hi = tuple(float(dtype(float(c))) for c in reversed(coeffs))
//       lo = tuple(float(dtype(float(c - mpmath.mpf(h))))
//                  for c, h in zip(reversed(coeffs), hi))
//       return hi, lo

